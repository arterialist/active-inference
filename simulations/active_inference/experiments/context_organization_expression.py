"""Separate learned expression from rapid online error-driven reacquisition.

Diagnostic lesion only, not an agent mechanism: clear information on the two
declared predictor error-receptor inputs immediately before each neural tick.
All rates remain positive, existing error/context traces persist and all other
adaptation runs. The lesion also removes native retrograde events generated by
those cleared arrivals. It is not an exact freeze of prediction weights.
Unlesioned reconstruction must match each complete original probe first.
"""
from contextlib import contextmanager
import argparse
import json
from pathlib import Path
import time

import numpy as np

from .context_organization import (Arm, course, digest, encode, load_checkpoint,
    PredictiveReceptorNeuron, verify_learning, verify_physics)


@contextmanager
def teaching_path_lesion(net,enabled):
    original=PredictiveReceptorNeuron.tick
    def tick(n,external_inputs,current_tick,dt=1.):
        if enabled and net.network.neurons.get(n.id) is n and n.prediction_ports:
            for sid,_ in n.prediction_error_ports:n.input_buffer[sid,0]=0.
        return original(n,external_inputs,current_tick,dt)
    PredictiveReceptorNeuron.tick=tick
    try:yield
    finally:PredictiveReceptorNeuron.tick=original


def run(source,output):
    source=Path(source).resolve();output=Path(output).resolve()
    m=json.loads((source/'manifest.json').read_text())
    old=json.loads((source/'summary.json').read_text())
    features=[]
    for clip in (0,1):
        paths=[Path(p) for p in m['physical_sources'] if Path(p).name==f'sensory-{clip}.npz']
        if len(paths)!=1 or digest(paths[0])!=m['physical_sources'][str(paths[0])]:raise ValueError('Media changed')
        with np.load(paths[0]) as z:features.append({k:z[k] for k in ('visual','auditory')})
    with np.load(source/'after-context-1-body.npz') as z:body_state=z['state']
    output.mkdir(exist_ok=False)
    manifest=dict(source=str(source),seed=m['seed'],contextual=m['contextual'],
        source_manifest_sha256=digest(source/'manifest.json'),source_sha256=digest(__file__),
        checkpoint_sha256=digest(source/'final.paula'),
        lesion='Suppress actual info arrivals on predictor error ports. Also removes their native retrograde responses. '
               'No parameter/rate freeze; prior error trace continues decaying.',
        physical_sources=m['physical_sources'],groups=m['groups'])
    (output/'manifest.json').write_text(encode(manifest)+'\n')
    results=[];began=time.perf_counter()
    for context in (0,1):
        for clip in (0,1):
            reference=next(r for r in old['probes'] if r['file']==f'probe-intact-c{context}-v{clip}.npz')
            if digest(source/reference['file'])!=reference['sha256']:raise ValueError('Reference changed')
            for lesion in (False,True):
                net=load_checkpoint(source/'final.paula',trusted=True).network
                body=Arm();body.restore(body_state)
                with teaching_path_lesion(net,lesion):
                    data=course(net,body,features,m['groups'],m['selected'],context,clip,reverse=m['reverse'])
                if not lesion:
                    with np.load(source/reference['file']) as z:
                        if set(z.files)!=set(data) or any(not np.array_equal(z[k],data[k]) for k in z.files):
                            raise ValueError('Unchanged expression replay differs')
                    continue
                name=f'lesion-c{context}-v{clip}.npz';np.savez_compressed(output/name,**data)
                result=dict(context=context,clip=clip,file=name,sha256=digest(output/name),
                    unchanged_replay_exact=True,learning_residual=verify_learning(data),
                    physics_residual=verify_physics(data),
                    min_eta=float(data['eta'].min()),
                    max_weight_change=float(abs(data['weights'][-1]-data['weights_initial']).max()))
                if np.any(data['errors'][:,:,1]!=0):raise ValueError('Lesion left incoming teaching info')
                results.append(result)
                print(encode(dict(context=context,clip=clip,seconds=time.perf_counter()-began)),flush=True)
    summary=dict(results=results,ticks=8*364,seconds=time.perf_counter()-began,
        interpretation='Expression-path diagnostic, not acceptance or proof of useful recall.')
    (output/'summary.json').write_text(encode(summary)+'\n');return summary


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('source',type=Path);p.add_argument('output',type=Path)
    a=p.parse_args();run(a.source,a.output)
